function renderHrReports() {
  const list = document.getElementById("hrReportList");
  list.innerHTML = "";
  siteData.hrReports.forEach((rep, idx) => {
    const div = document.createElement("div");
    div.className = `hr-report-card ${idx === 0 ? "active" : ""}`;
    div.innerHTML = `
      <h4>${rep.title}</h4>
      <span style="font-size:0.85rem; color:#64748b;">${rep.date}</span>
    `;
    div.onclick = () => {
      document.querySelectorAll(".hr-report-card").forEach((c) => c.classList.remove("active"));
      div.classList.add("active");
      document.getElementById("activePdfTitle").textContent = rep.title;
      document.getElementById("pdfFrame").src = rep.file;
      document.getElementById("downloadPdfBtn").href = rep.file;
    };
    list.appendChild(div);
  });
}

