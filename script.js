let siteData = JSON.parse(localStorage.getItem("pccpSiteData")) || defaultData;

document.getElementById("menuToggle").addEventListener("click", () => {
  document.getElementById("navMenu").classList.toggle("active");
});

function openReader(title, date, body, image = "") {
  document.getElementById("readerTitle").textContent = title;
  document.getElementById("readerMeta").textContent = date;
  document.getElementById("readerContent").textContent = body;
  const imgEl = document.getElementById("readerImg");
  if (image) {
    imgEl.src = image;
    imgEl.style.display = "block";
  } else {
    imgEl.style.display = "none";
  }
  document.getElementById("readerModal").style.display = "block";
}

document.getElementById("closeReaderBtn").onclick = () => {
  document.getElementById("readerModal").style.display = "none";
};

function renderCards(items, containerId) {
  const container = document.getElementById(containerId);
  container.innerHTML = "";
  items.forEach((item) => {
    const card = document.createElement("div");
    card.className = "card";
    card.innerHTML = `
      ${item.image ? `<img src="${item.image}" alt="${item.title}">` : ""}
      <div class="card-body">
        <span class="meta-date">${item.date}</span>
        <h3 class="card-title">${item.title}</h3>
        <p class="card-text">${item.body.slice(0, 115)}...</p>
        <button class="read-more-btn">বিস্তারিত পড়ুন →</button>
      </div>
    `;
    card.querySelector(".read-more-btn").onclick = () => openReader(item.title, item.date, item.body, item.image);
    container.appendChild(card);
  });
}

function renderPress() {
  const list = document.getElementById("pressList");
  list.innerHTML = "";
  siteData.press.forEach((p) => {
    const div = document.createElement("div");
    div.className = "press-item";
    div.innerHTML = `
      <div>
        <span class="meta-date">${p.date}</span>
        <h3>${p.title}</h3>
      </div>
      <button class="btn btn-green btn-sm">বিজ্ঞপ্তি পড়ুন</button>
    `;
    div.querySelector("button").onclick = () => openReader(p.title, p.date, p.body);
    list.appendChild(div);
  });
}

function renderCommittees(filter = "central") {
  const container = document.getElementById("committeeContainer");
  container.innerHTML = "";
  const filtered = siteData.committees.filter((c) => c.unit === filter);
  filtered.forEach((m) => {
    const div = document.createElement("div");
    div.className = "member-card";
    div.innerHTML = `
      <img src="logo.jpg" alt="${m.name}" class="member-avatar" />
      <h4>${m.name}</h4>
      <span class="role-tag">${m.role}</span>
      <p style="font-size:0.9rem; color:#475569;">${m.area}</p>
      <p style="font-size:0.85rem; margin-top:4px;">যোগাযোগ: ${m.phone}</p>
    `;
    container.appendChild(div);
  });
}

document.querySelectorAll(".tab-btn").forEach((btn) => {
  btn.addEventListener("click", () => {
    document.querySelectorAll(".tab-btn").forEach((b) => b.classList.remove("active"));
    btn.classList.add("active");
    renderCommittees(btn.dataset.filter);
  });
});

