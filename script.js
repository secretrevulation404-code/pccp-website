document.getElementById("publishForm").addEventListener("submit", (e) => {
  e.preventDefault();
  const cat = document.getElementById("postCategory").value;
  const newPost = {
    title: document.getElementById("postTitle").value,
    date: document.getElementById("postDate").value,
    image: document.getElementById("postImage").value,
    body: document.getElementById("postBody").value
  };

  if (cat === "press") siteData.press.unshift(newPost);
  if (cat === "feature") siteData.features.unshift(newPost);
  if (cat === "update") siteData.updates.unshift(newPost);
  if (cat === "program") siteData.programs.unshift(newPost);

  localStorage.setItem("pccpSiteData", JSON.stringify(siteData));
  renderAll();
  e.target.reset();
  adminModal.style.display = "none";
  alert("সফলভাবে ওয়েবসাইটে প্রকাশিত হয়েছে!");
});

